/** 이름으로 분류와 이모지를 추정한다 (직접 입력한 재료, 옛 데이터용) */
export function guessFood(name: string): { category: FoodCategory; emoji: string } {
  const n = name.replace(/\s+/g, "");
  for (const [re, category, emoji] of KEYWORDS) if (re.test(n)) return { category, emoji };
  return { category: "기타", emoji: CATEGORY_EMOJI["기타"] };
}

/** 냉장고 안의 칸 */
export const FridgeZone = z.enum(["freezer", "top", "middle", "bottom", "crisper", "door", "pantry"]);
export type FridgeZone = z.infer<typeof FridgeZone>;

export const ZONE_LABEL: Record<FridgeZone, string> = {
  freezer: "냉동실", top: "윗칸 · 유제품·달걀", middle: "가운데 칸 · 반찬·기타", bottom: "아랫칸 · 고기·생선",
  crisper: "야채칸", door: "문 칸 · 음료·소스", pantry: "실온 보관장",
};

/** 보관 위치 + 분류 → 냉장고 칸 */
export function fridgeZone(location: "냉장" | "냉동" | "실온", category: FoodCategory): FridgeZone {
  if (location === "냉동") return "freezer";
  if (location === "실온") return "pantry";
  switch (category) {
    case "음료": case "소스·양념": return "door";
    case "유제품": case "달걀": case "두부·콩": return "top";
    case "육류": case "해산물": return "bottom";
    case "채소": case "과일": return "crisper";
    default: return "middle";
  }
}
